# Set PG_CONF_DIR and PG_DATA_DIR for major version $1
pg_paths() {
	case $SMAP_FAMILY in
		debian)
			PG_CONF_DIR=/etc/postgresql/$1/main
			PG_DATA_DIR=/var/lib/postgresql/$1/main
			;;
		rhel|suse)
			PG_CONF_DIR=/var/lib/pgsql/data
			PG_DATA_DIR=/var/lib/pgsql/data
			;;
		arch)
			PG_CONF_DIR=/var/lib/postgres/data
			PG_DATA_DIR=/var/lib/postgres/data
			;;
	esac
}

# Create the database cluster.  Debian creates one when the package is installed.  Does
# nothing if the cluster already exists
pg_initdb() {
	[ -f $PG_DATA_DIR/PG_VERSION ] && return 0
	case $SMAP_FAMILY in
		debian) ;;
		rhel) postgresql-setup --initdb ;;
		suse) systemctl start $PG_SERVICE ;;		# The service creates the cluster on its first start
		arch) su - postgres -s /bin/sh -c "initdb --locale=C.UTF-8 --encoding=UTF8 --auth-local=peer --auth-host=scram-sha-256 -D $PG_DATA_DIR" ;;
	esac
}

#
# Version check
#
# Run before anything is installed or changed.  Asks the package manager which version of
# each component it would install, prints them against the versions Smap needs and returns
# false if any required one is missing or too old, so that the install can stop while the
# server is still as it was.  Call pkg_update first so the versions are current.
#
# $1 is "remote" if the database is on another server, in which case only the PostgreSQL
# client is needed here.
#
# Sets SMAP_PG_VERSION to the PostgreSQL major version that will be installed, and switches
# to the Tomcat tarball locations if the package is too old but the tarball is allowed.
#

check_row() {
	printf '%-12s %-10s %-24s %s\n' "$1" "$2" "${3:-none}" "$4"
}

check_note() {
	printf '%-48s %s\n' "" "$1"
}

# Record the result of one check.  $1 is the version found, $2 the minimum
check_version() {
	if version_ge "$1" "$2"; then
		_result=ok
	else
		_result=FAIL
		_failed=yes
	fi
}

# Every package in the list must be available
check_available() {
	for _p in "$@"
	do
		_v=`pkg_candidate $_p`
		if [ -z "$_v" ]; then
			check_note "FAIL: package $_p not available"
			_failed=yes
		fi
	done
}

# What stops working without an optional package
optional_feature() {
	case $1 in
		imagemagick|ImageMagick) echo "photo thumbnails" ;;
		ffmpeg*) echo "video thumbnails and audio conversion" ;;
		*exif*|*Exif*) echo "keeping exif data in resized photos" ;;
		gdal*) echo "shapefile and KML export" ;;
		zip) echo "zip downloads" ;;
		*dejavu*) echo "fonts in PDF reports" ;;
		*) echo "$1" ;;
	esac
}

platform_check_versions() {
	_db=$1
	_failed=""
	_hints=""

	echo "Checking the versions $SMAP_OS_NAME provides"
	check_row "Component" "Needed" "Available" ""

	_v=`pkg_candidate $PKG_JAVA`
	check_version "$_v" $SMAP_MIN_JAVA
	check_row "Java" "$SMAP_MIN_JAVA" "$_v" $_result

	_v=`pkg_candidate $PKG_TOMCAT`
	if version_ge "$_v" $SMAP_MIN_TOMCAT && ! tomcat_package_unpatched; then
		_result=ok
	elif tomcat_tarball_allowed; then
		tomcat_use_tarball
		if version_ge "$_v" $SMAP_MIN_TOMCAT; then
			_result="ok, tarball $SMAP_TOMCAT_TARBALL_VERSION will be used as the package gets no security fixes without Ubuntu Pro"
		else
			_result="ok, tarball $SMAP_TOMCAT_TARBALL_VERSION will be used"
		fi
	elif version_ge "$_v" $SMAP_MIN_TOMCAT; then
		_result="ok, but the package gets no security fixes without Ubuntu Pro"
	else
		_result=FAIL
		_failed=yes
	fi
	check_row "Tomcat" "$SMAP_MIN_TOMCAT" "$_v" "$_result"

	set -- $PKG_APACHE
	_v=`pkg_candidate $1`
	check_version "$_v" $SMAP_MIN_APACHE
	check_row "Apache" "$SMAP_MIN_APACHE" "$_v" $_result
	shift
	check_available "$@"

	if [ "$_db" = "remote" ]; then
		check_available $PKG_PG_CLIENT
		SMAP_PG_VERSION=""
	else
		set -- $PKG_PG_SERVER
		_v=`pkg_candidate $1`
		SMAP_PG_VERSION=`version_major "$_v"`
		check_version "$_v" $SMAP_MIN_POSTGRES
		check_row "PostgreSQL" "$SMAP_MIN_POSTGRES" "$_v" $_result
		if [ $_result = "FAIL" ] && [ $SMAP_FAMILY = "rhel" ]; then
			_hints="$_hints
A newer PostgreSQL may be available as a module stream, see: dnf module list postgresql
For example: dnf module enable postgresql:16"
		fi
		shift
		check_available "$@"

		_p=`pkg_postgis $SMAP_PG_VERSION`
		_v=`pkg_candidate $_p`
		check_version "$_v" $SMAP_MIN_POSTGIS
		check_row "PostGIS" "$SMAP_MIN_POSTGIS" "$_v" "$_result ($_p)"
		if [ $_result = "FAIL" ] && [ $SMAP_FAMILY = "suse" ]; then
			_hints="$_hints
PostGIS is in the openSUSE Application:Geo repository, which needs to be added"
		fi
	fi

	# Optional packages are reported but do not stop the install
	for _p in $PKG_MEDIA $PKG_UTILS
	do
		if [ -z "`pkg_candidate $_p`" ]; then
			check_note "warning: $_p not available, no `optional_feature $_p`"
		fi
	done

	if [ -n "$_failed" ]; then
		echo ""
		echo "ERROR: $SMAP_OS_NAME does not provide the versions Smap needs.  Nothing has been changed.$_hints"
		return 1
	fi
	return 0
}

#
# Saved settings
#

# A setting from the environment, or from /etc/environment when sudo has not passed it on
env_value() {
	eval _val=\$$1
	[ -n "$_val" ] || _val=`sed -n "s/^$1=//p" /etc/environment 2>/dev/null | tr -d '"' | tail -1`
	echo "$_val"
}

# A server built with WEBSITE=no only runs the subscribers, it has no Tomcat or Apache
platform_web() {
	[ "`env_value WEBSITE`" != "no" ]
}

platform_local_db() {
	_h=`env_value DBHOST`
	[ -z "$_h" ] || [ "$_h" = "127.0.0.1" ]
}

# Major version of the local PostgreSQL server that is running, which is the one Smap uses
# when more than one is installed
pg_server_major() {
	[ "`id -u`" = "0" ] || return 0
	_n=`su postgres -s /bin/sh -c "psql -tAc 'show server_version_num'" 2>/dev/null`
	[ -n "$_n" ] && echo $((_n / 10000))
}

# Work out where the components are on a server installed before platform.conf existed.
# Those were all Ubuntu, with Tomcat from either the packages or the tarball
platform_discover() {
	if [ $SMAP_FAMILY = "debian" ] && [ -f /var/lib/tomcat10/bin/catalina.sh ]; then
		tomcat_use_tarball
	fi
	if platform_local_db; then
		SMAP_PG_VERSION=`pg_server_major`
		if [ -z "$SMAP_PG_VERSION" ]; then
			case $SMAP_FAMILY in
				debian) SMAP_PG_VERSION=`ls /etc/postgresql 2>/dev/null | sort -n | tail -1` ;;
				*) pg_paths; SMAP_PG_VERSION=`cat $PG_DATA_DIR/PG_VERSION 2>/dev/null` ;;
			esac
		fi
		pg_paths $SMAP_PG_VERSION
	fi
}

validate_path() {
	[ -e "$1" ] || _missing="$_missing
  $1"
}

validate_service() {
	systemctl cat $1 > /dev/null 2>&1 || _missing="$_missing
  service $1"
}

# Check that everything the settings point to is on this server
platform_validate() {
	_missing=""
	id $TOMCAT_USER > /dev/null 2>&1 || _missing="$_missing
  user $TOMCAT_USER"
	if platform_web; then
		validate_path $TOMCAT_INSTALL_DIR/lib/catalina.jar
		validate_path $TOMCAT_CONF_DIR/server.xml
		validate_path $TOMCAT_WEBAPPS
		validate_path $TOMCAT_LIB
		validate_service $TOMCAT_SERVICE
		command -v $APACHECTL > /dev/null || _missing="$_missing
  command $APACHECTL"
		validate_path $APACHE_SITE_DIR
		validate_service $APACHE_SERVICE
	fi
	if platform_local_db; then
		validate_path $PG_CONF_DIR/postgresql.conf
		validate_service $PG_SERVICE
	fi
	if [ -n "$_missing" ]; then
		echo "ERROR: These were expected on this server but were not found:$_missing"
		return 1
	fi
	return 0
}

platform_save() {
	mkdir -p `dirname $SMAP_PLATFORM_CONF`
	{
		echo "# Written by Smap on `date +%Y-%m-%d`, $SMAP_OS_NAME"
		echo "#"
		echo "# Where this server's components are, read by the install and deploy scripts."
		echo "# Delete this file to have deploy.sh detect them again."
		for _s in $SMAP_PLATFORM_SETTINGS
		do
			eval _val=\$$_s
			printf '%s="%s"\n' $_s "$_val"
		done
	} > $SMAP_PLATFORM_CONF
	chmod 644 $SMAP_PLATFORM_CONF
	echo "Saved this server's settings in $SMAP_PLATFORM_CONF"
}

# Check the versions that are installed, when deploying.  PostgreSQL only gets a warning, as
# a server upgraded from an older release can still be running the older version's cluster
platform_check_installed() {
	_failed=""
	echo "Checking the versions installed"
	check_row "Component" "Needed" "Installed" ""

	_v=`java -version 2>&1 | sed -n 's/.*version "\([^"]*\)".*/\1/p' | head -1`
	check_version "$_v" $SMAP_MIN_JAVA
	check_row "Java" "$SMAP_MIN_JAVA" "$_v" $_result

	if platform_web; then
		_v=`java -cp $TOMCAT_INSTALL_DIR/lib/catalina.jar org.apache.catalina.util.ServerInfo 2>/dev/null | sed -n 's/^Server number: *//p'`
		check_version "$_v" $SMAP_MIN_TOMCAT
		check_row "Tomcat" "$SMAP_MIN_TOMCAT" "$_v" $_result

		_v=`$APACHECTL -v 2>/dev/null | sed -n 's|^Server version: Apache/\([0-9.]*\).*|\1|p'`
		check_version "$_v" $SMAP_MIN_APACHE
		check_row "Apache" "$SMAP_MIN_APACHE" "$_v" $_result
	fi

	if platform_local_db; then
		_v=`pg_server_major`
		_v=${_v:-$SMAP_PG_VERSION}
		if version_ge "$_v" $SMAP_MIN_POSTGRES; then
			_result=ok
		else
			_result="warning, upgrade to $SMAP_MIN_POSTGRES or later"
		fi
		check_row "PostgreSQL" "$SMAP_MIN_POSTGRES" "$_v" "$_result"
	fi

	if [ -n "$_failed" ]; then
		echo ""
		echo "ERROR: This server does not have the versions Smap needs."
		return 1
	fi
	return 0
}

# Used by the deploy scripts.  Loads the saved settings or, on a server installed before they
# were saved, detects and saves them.  Then checks the installed versions
platform_setup() {
	platform_detect || return 1
	if [ -f $SMAP_PLATFORM_CONF ]; then
		. $SMAP_PLATFORM_CONF
		if ! platform_validate; then
			echo "The settings came from $SMAP_PLATFORM_CONF.  Correct it, or delete it to have them detected again"
			return 1
		fi
	else
		echo "Detecting this server's settings, as there is no $SMAP_PLATFORM_CONF"
		platform_discover
		platform_validate || return 1
		platform_save
	fi
	platform_check_installed
}

