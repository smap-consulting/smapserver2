# True if this RHEL, or Ubuntu LTS release, may use the Tomcat tarball
tomcat_tarball_allowed() {
	[ $SMAP_FAMILY = "rhel" ] && [ "$SMAP_OS_ID" != "fedora" ] && return 0
	[ "$SMAP_OS_ID" = "ubuntu" ] || return 1
	_now=`date +%Y%m`
	for _r in $SMAP_TOMCAT_TARBALL_RELEASES
	do
		if [ "${_r%%:*}" = "$SMAP_OS_VERSION" ] && [ "$_now" -lt "${_r#*:}" ]; then
			return 0
		fi
	done
	return 1
}

# True if Tomcat would come from Ubuntu's universe repository, which only gets security fixes
# through Ubuntu Pro (ESM), on a server that does not have it
tomcat_package_unpatched() {
	[ "$SMAP_OS_ID" = "ubuntu" ] || return 1
	case `apt-cache show --no-all-versions $PKG_TOMCAT 2>/dev/null | sed -n 's/^Section: //p' | head -1` in
		universe/*|multiverse/*) ;;
		*) return 1 ;;
	esac
	! pro status 2>/dev/null | grep -Eq '^esm-apps[[:space:]].*[[:space:]]enabled'
}

# Locations used by the tarball install, which is all under /var/lib/tomcat10
tomcat_use_tarball() {
	TOMCAT_TARBALL=yes
	TOMCAT_SERVICE=tomcat10
	TOMCAT_USER=tomcat
	TOMCAT_INSTALL_DIR=/var/lib/tomcat10
	TOMCAT_BASE_DIR=/var/lib/tomcat10
	TOMCAT_CONF_DIR=/var/lib/tomcat10/conf
	TOMCAT_WEBAPPS=/var/lib/tomcat10/webapps
	TOMCAT_LIB=/var/lib/tomcat10/lib
}

java_home() {
	readlink -f `command -v java` | sed "s:/bin/java$::"
}

#
# Apache
#

apache_enable_module() {
	case $SMAP_FAMILY in
		debian|suse) a2enmod $1 ;;
		rhel|arch)
			# Most modules are loaded by the stock configuration.  Any that are not are
			# loaded from a file of Smap's own so the distribution's files are left alone
			if [ $SMAP_FAMILY = "rhel" ]; then
				_conf=/etc/httpd/conf.modules.d/99-smap.conf
			else
				_conf=/etc/httpd/conf/smap-modules.conf
				apache_include $_conf
			fi
			# mod_ssl needs a session cache, which Debian enables along with it
			[ $1 = "ssl" ] && apache_enable_module socache_shmcb
			if ! $APACHECTL -M 2>/dev/null | grep -q " $1_module"; then
				grep -qs "^LoadModule $1_module " $_conf || echo "LoadModule $1_module modules/mod_$1.so" >> $_conf
			fi
			;;
	esac
}

# Switch on a site file that is in APACHE_SITE_DIR
apache_enable_site() {
	case $SMAP_FAMILY in
		debian) a2ensite $1 ;;
		rhel) ln -sf $APACHE_SITE_DIR/$1 /etc/httpd/conf.d/$1 ;;
		suse) ln -sf $APACHE_SITE_DIR/$1 /etc/apache2/vhosts.d/$1 ;;
		arch)
			mkdir -p /etc/httpd/conf/smap-enabled
			ln -sf $APACHE_SITE_DIR/$1 /etc/httpd/conf/smap-enabled/$1
			apache_include "/etc/httpd/conf/smap-enabled/*.conf"
			;;
	esac
}

apache_disable_site() {
	case $SMAP_FAMILY in
		debian) a2dissite $1 ;;
		rhel) rm -f /etc/httpd/conf.d/$1 ;;
		suse) rm -f /etc/apache2/vhosts.d/$1 ;;
		arch) rm -f /etc/httpd/conf/smap-enabled/$1 ;;
	esac
}

# Arch's httpd.conf does not read any directory of extra configuration, so add one line for
# each of Smap's files
apache_include() {
	grep -qsF "IncludeOptional $1" /etc/httpd/conf/httpd.conf || echo "IncludeOptional $1" >> /etc/httpd/conf/httpd.conf
}

#
# PostgreSQL
