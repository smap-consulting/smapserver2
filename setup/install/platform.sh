#!/bin/sh
##### Platform detection for the install and deploy scripts
#
# Usage: . ./platform.sh             Sourced by install.sh, deploy.sh, patchdb.sh etc
#        sh platform.sh show         Print what was detected for this machine
#
# Smap can be installed on any Linux whose package manager is one of apt, dnf, zypper or
# pacman, as long as its packages provide the versions Smap needs (see the SMAP_MIN_*
# settings).  This file works out which family of Linux this is and sets, for that family,
# the package names, service names, users and file locations the other scripts use, so
# that they do not have to test for particular distributions themselves.
#
# The distribution is read from /etc/os-release, which every current distribution has.
# lsb_release, used previously, is not installed on minimal Debian, RHEL or Arch images.
# Set SMAP_OS_RELEASE to read another file, for testing.
#
# Values marked "verify" have not yet been checked on a real install of that family.

# Minimum versions.  The install refuses to start if the packages are older than these.
SMAP_MIN_JAVA=11			# the code is built for Java 11, which Tomcat 10.1 also needs; new installs get 21
SMAP_MIN_TOMCAT=10.1
SMAP_MIN_APACHE=2.4
SMAP_MIN_POSTGRES=14
SMAP_MIN_POSTGIS=3

# Tomcat has to come from the distribution's packages.  The exceptions, which get the tarball
# from apache.org instead, are RHEL and its rebuilds, which have no Tomcat 10.1 package, and an
# Ubuntu LTS release that is still in standard support but whose packages do not have Tomcat
# 10.1.  Each entry is release:end of standard support (year and month).  Remove a release
# once its support ends.
SMAP_TOMCAT_TARBALL_RELEASES="22.04:202704 24.04:202904 26.04:203104"
SMAP_TOMCAT_TARBALL_VERSION=10.1.40

# Apache modules that Smap's configuration uses
SMAP_APACHE_MODULES="auth_digest expires dbd authn_dbd proxy proxy_ajp ssl headers request auth_form session session_cookie session_crypto"

SMAP_OS_RELEASE=${SMAP_OS_RELEASE:-/etc/os-release}

# Where this server's components are, saved by platform_save so that later deploys use what
# was installed rather than detecting it again.  These are the settings it holds.
SMAP_PLATFORM_CONF=${SMAP_PLATFORM_CONF:-/etc/smap/platform.conf}
SMAP_PLATFORM_SETTINGS="SMAP_FAMILY TOMCAT_TARBALL TOMCAT_SERVICE TOMCAT_USER TOMCAT_INSTALL_DIR TOMCAT_BASE_DIR TOMCAT_CONF_DIR TOMCAT_WEBAPPS TOMCAT_LIB APACHE_SERVICE APACHE_USER APACHECTL APACHE_SITE_DIR APACHE_LOG_DIR SMAP_PG_VERSION PG_SERVICE PG_HOME PG_CONF_DIR PG_DATA_DIR SSL_CERT_FILE SSL_KEY_FILE"

# Read one value from os-release without sourcing it, as it would overwrite variables
# such as NAME and VERSION in the calling script
os_release_value() {
	sed -n "s/^$1=//p" $SMAP_OS_RELEASE | tr -d '"' | tail -1
}

platform_detect() {
	if [ ! -f "$SMAP_OS_RELEASE" ]; then
		echo "ERROR: $SMAP_OS_RELEASE not found, cannot tell which Linux this is"
		return 1
	fi

	SMAP_OS_ID=`os_release_value ID`
	SMAP_OS_VERSION=`os_release_value VERSION_ID`
	SMAP_OS_NAME=`os_release_value PRETTY_NAME`
	SMAP_FAMILY=""

	# ID_LIKE lists the distributions this one is derived from, for example "rhel centos
	# fedora" on Rocky, so derivatives that are not named here are still recognised
	for id in $SMAP_OS_ID `os_release_value ID_LIKE`
	do
		case $id in
			debian|ubuntu) SMAP_FAMILY=debian ;;
			rhel|fedora|centos) SMAP_FAMILY=rhel ;;
			suse|opensuse|opensuse-leap|opensuse-tumbleweed|sles) SMAP_FAMILY=suse ;;
			arch) SMAP_FAMILY=arch ;;
		esac
		[ -n "$SMAP_FAMILY" ] && break
	done

	if [ -z "$SMAP_FAMILY" ]; then
		echo "ERROR: $SMAP_OS_NAME is not supported.  Smap needs a Linux that uses apt, dnf, zypper or pacman"
		return 1
	fi

	platform_$SMAP_FAMILY
}

