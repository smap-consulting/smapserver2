# Refresh the list of available packages, so pkg_candidate sees current versions.  Nothing
# is installed or upgraded
pkg_update() {
	case $SMAP_FAMILY in
		debian) apt-get update ;;
		rhel) dnf -y makecache ;;
		suse) zypper --non-interactive refresh ;;
		arch) pacman -Sy ;;
	esac
}

pkg_install() {
	case $SMAP_FAMILY in
		debian) DEBIAN_FRONTEND=noninteractive apt-get install -y "$@" ;;
		rhel) dnf install -y "$@" ;;
		suse) zypper --non-interactive install "$@" ;;
		# Arch does not support installing packages from a refreshed list without upgrading
		# the rest of the system to match
		arch) pacman -Syu --noconfirm --needed "$@" ;;
	esac
}

# The version the package manager would install, or nothing if it has no such package
pkg_candidate() {
	case $SMAP_FAMILY in
		debian) apt-cache policy "$1" 2>/dev/null | awk '/Candidate:/ { print $2 }' | grep -v '(none)' ;;
		rhel) dnf -q info "$1" 2>/dev/null | awk -F': *' '/^Version/ { print $2; exit }' ;;
		suse) zypper -q info "$1" 2>/dev/null | awk -F': *' '/^Version/ { print $2; exit }' ;;
		arch) pacman -Si "$1" 2>/dev/null | awk -F': *' '/^Version/ { print $2; exit }' ;;
	esac
}

# PostGIS is built for each PostgreSQL major version on some families
pkg_postgis() {
	case $SMAP_FAMILY in
		debian) echo "postgresql-$1-postgis-3" ;;
		*) echo "postgis" ;;		# suse verify: comes from the Application:Geo repository
	esac
}

# Strip the epoch, Debian revision and release from a package version, 1:16+257 -> 16,
# 10.1.40-1 -> 10.1.40
version_clean() {
	echo "$1" | sed 's/^[0-9]*://; s/[-+~].*//'
}

# True if version $1 is $2 or later
version_ge() {
	_v1=`version_clean "$1"`
	_v2=`version_clean "$2"`
	[ -n "$_v1" ] && [ "`printf '%s\n%s\n' "$_v2" "$_v1" | sort -V | head -1`" = "$_v2" ]
}

# Major version, 16.4 -> 16
version_major() {
	version_clean "$1" | cut -d. -f1
}

