# Make a self signed certificate if the family does not provide one
ssl_ensure_self_signed() {
	[ -f $SSL_CERT_FILE ] && [ -f $SSL_KEY_FILE ] && return 0
	case $SSL_CERT_FILE in
		/etc/smap/*)
			mkdir -p `dirname $SSL_CERT_FILE`
			openssl req -x509 -nodes -newkey rsa:2048 -days 3650 -subj "/CN=${1:-localhost}" \
				-keyout $SSL_KEY_FILE -out $SSL_CERT_FILE
			chmod 600 $SSL_KEY_FILE
			;;
	esac
}

